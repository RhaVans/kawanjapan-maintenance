import { defineConfig, type Plugin } from 'vite';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, renameSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { COPY } from './src/copy';

function esc(s: string) {
  return s.replace(/[<>&"]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;' })[c]!);
}

/**
 * The page is served by a function so it can answer 503 with Retry-After, which
 * a static host cannot do. Fonts are renamed to their content hash: /assets is
 * immutable for a year, so a stable filename would pin a stale subset.
 */
function pageAndFonts(): Plugin {
  return {
    name: 'page-and-hashed-fonts',
    apply: 'build',
    closeBundle() {
      const dir = 'dist/assets/fonts';
      let html = readFileSync('dist/index.html', 'utf8');
      for (const file of readdirSync(dir)) {
        if (!file.endsWith('.woff2')) continue;
        const bytes = readFileSync(join(dir, file));
        const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 8);
        const hashed = file.replace(/\.woff2$/, `.${hash}.woff2`);
        renameSync(join(dir, file), join(dir, hashed));
        html = html.replaceAll(`/assets/fonts/${file}`, `/assets/fonts/${hashed}`);
      }
      writeFileSync('dist/index.html', html);

      const success = {
        id: esc(COPY.id.success),
        en: esc(COPY.en.success),
        ja: esc(COPY.ja.success),
      };
      const source = `// Generated by vite.config.ts from dist/index.html. Do not edit.
const HTML = ${JSON.stringify(html)};
const SUCCESS = ${JSON.stringify(success)};

function pickLang(url, accept) {
  const q = url.searchParams.get('lang');
  if (q === 'id' || q === 'en' || q === 'ja') return q;
  for (const part of String(accept || '').split(',')) {
    const tag = part.split(';')[0].trim().toLowerCase().split('-')[0];
    if (tag === 'ja') return 'ja';
    if (tag === 'en') return 'en';
  }
  return 'id';
}

export default function handler(req, res) {
  const url = new URL(req.url, 'https://' + (req.headers.host || 'localhost'));
  const lang = pickLang(url, req.headers['accept-language']);
  let html = HTML.replace('<html lang="id"', '<html lang="' + lang + '"');
  html = html.replace('name="ts" value="0"', 'name="ts" value="' + Date.now() + '"');
  if (url.searchParams.get('ok') === '1') {
    const done = '<p class="notify-done" role="status" aria-live="polite" data-i18n="success">' + SUCCESS[lang] + '</p>';
    html = html.replace(/<!--form-->[\\s\\S]*?<!--\\/form-->/, done);
  }
  res.statusCode = 503;
  res.setHeader('content-type', 'text/html; charset=utf-8');
  res.setHeader('cache-control', 'no-store');
  res.setHeader('retry-after', '3600');
  res.end(html);
}
`;
      mkdirSync('api', { recursive: true });
      writeFileSync('api/page.js', source);
    },
  };
}

export default defineConfig({
  plugins: [pageAndFonts()],
  build: { target: 'es2022' },
});
